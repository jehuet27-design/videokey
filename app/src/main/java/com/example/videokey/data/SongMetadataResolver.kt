    /**
     * Resolves song metadata (title, artist, category) given code, raw title, and raw artist.
     * Guarantees that artist will NEVER be "Unknown" or blank.
     */
    fun resolve(code: String, rawTitle: String, rawArtist: String): ResolvedSongMeta {
        val trimmedCode = code.trim()
        val trimmedTitle = rawTitle.trim()
        val trimmedArtist = rawArtist.trim()

        // 1. Check code in curated knowledge base
        val byCode = CODE_MAP[trimmedCode] ?: CODE_MAP[trimmedCode.trimStart('0')]
        if (byCode != null) {
            // If raw title has good casing or user customized it, keep it, but ensure artist is genuine
            val finalTitle = if (trimmedTitle.isNotBlank() && !trimmedTitle.equals(trimmedCode, true) && !trimmedTitle.equals("Unknown", true)) {
                cleanTitle(trimmedTitle)
            } else {
                byCode.title
            }
            val finalArtist = if (isValidArtist(trimmedArtist)) trimmedArtist else byCode.artist
            return ResolvedSongMeta(finalTitle, finalArtist, byCode.category)
        }

        // 2. Clean raw title if it starts with code (e.g. "01234 - Song Title")
        val cleanedTitle = cleanTitle(trimmedTitle)

        // 3. If raw artist is already valid, return with cleaned title
        if (isValidArtist(trimmedArtist)) {
            val cat = detectCategory(cleanedTitle, trimmedArtist)
            return ResolvedSongMeta(cleanedTitle, trimmedArtist, cat)
        }

        // 4. Try matching title in knowledge base
        val normTitle = normalizeTitle(cleanedTitle)
        val matchedArtist = TITLE_MAP[normTitle]
        if (matchedArtist != null) {
            val cat = detectCategory(cleanedTitle, matchedArtist)
            return ResolvedSongMeta(cleanedTitle, matchedArtist, cat)
        }

        // 5. Check if title has embedded artist: "Title - Artist", "Artist - Title", "Title by Artist", "Title (Artist)"
        val embedded = extractEmbeddedArtist(cleanedTitle)
        if (embedded != null) {
            val cat = detectCategory(embedded.first, embedded.second)
            return ResolvedSongMeta(embedded.first, embedded.second, cat)
        }

        // 6. Check common patterns: Fanfare, Jingle, Children Rhyme, Hymn
        val titleLower = cleanedTitle.lowercase(Locale.ROOT)
        val (fallbackArtist, fallbackCat) = when {
            titleLower.contains("fanfare") || titleLower.contains("jingle") || titleLower.contains("sound effect") ->
                Pair("Videoke Sound Effects", "SOUND_EFFECTS")
            titleLower.contains("awit") || titleLower.contains("bibe") || titleLower.contains("nursery") || titleLower.contains("rhyme") ->
                Pair("Awiting Pambata", "CHILDREN")
            titleLower.contains("hymn") || titleLower.contains("papuri") || titleLower.contains("worship") || titleLower.contains("jesus") || titleLower.contains("diyos") ->
                Pair("Praise & Worship", "CHRISTIAN")
            else ->
                Pair("OPM / Videoke Hits", "OPM")
        }

        return ResolvedSongMeta(cleanedTitle, fallbackArtist, fallbackCat)
    }

    /**
     * Checks if an artist string is genuinely valid (not "Unknown", not "Karaoke", not empty).
     */
    fun isValidArtist(artist: String?): Boolean {
        if (artist == null) return false
        val a = artist.trim()
        if (a.isEmpty()) return false
        val lower = a.lowercase(Locale.ROOT)
        return lower != "unknown" &&
                lower != "unknown artist" &&
                lower != "hindi kilalang artist" &&
                lower != "karaoke" &&
                lower != "minus-one" &&
                lower != "midi" &&
                lower != "track" &&
                lower != "artist"
    }

    /**
     * Helper to get clean artist for display in UI, ensuring "Unknown" is never shown.
     */
    fun getDisplayArtist(song: Song): String {
        if (isValidArtist(song.artist)) return song.artist
        val resolved = resolve(song.code, song.title, song.artist)
        return resolved.artist
    }

    /**
     * Strips leading track numbers, timestamps, and redundant tags from song titles.
     */
    fun cleanTitle(rawTitle: String): String {
        var t = rawTitle.trim()
        // Strip leading numbers: "01234 - Title", "01234. Title", "01234_Title"
        t = t.replace(Regex("^\\d{4,6}\\s*[-_.:]\\s*"), "")
        // Strip file extensions if accidentally kept
        t = t.replace(Regex("(?i)\\.(mid|kar|mp4|mkv|mp3)$"), "")
        // Clean leading or trailing dashes / underscores
        t = t.trim('-', '_', ' ')
        return if (t.isEmpty()) rawTitle else t
    }

    private fun normalizeTitle(title: String): String {
        return title.replace(Regex("[^a-zA-Z0-9]+"), " ").trim().uppercase(Locale.ROOT)
    }

    private fun extractEmbeddedArtist(title: String): Pair<String, String>? {
        // "Title - Artist"
        if (title.contains(" - ")) {
            val parts = title.split(" - ", limit = 2)
            if (parts.size == 2 && parts[0].trim().isNotEmpty() && parts[1].trim().isNotEmpty()) {
                val t = parts[0].trim()
                val a = parts[1].trim()
                if (isValidArtist(a)) return Pair(t, a)
            }
        }
        // "Title (Artist)"
        val parenMatch = Regex("^(.+?)\\s*\\(([^()]+)\\)$").find(title)
        if (parenMatch != null) {
            val (t, a) = parenMatch.destructured
            if (isValidArtist(a.trim())) {
                return Pair(t.trim(), a.trim())
            }
        }
        // "Title by Artist"
        val byMatch = Regex("^(.+?)\\s+by\\s+(.+?)$", RegexOption.IGNORE_CASE).find(title)
        if (byMatch != null) {
            val (t, a) = byMatch.destructured
            if (isValidArtist(a.trim())) {
                return Pair(t.trim(), a.trim())
            }
        }
        return null
    }

    private fun detectCategory(title: String, artist: String): String {
        val combined = "${title.lowercase(Locale.ROOT)} ${artist.lowercase(Locale.ROOT)}"
        return when {
            combined.contains("praise") || combined.contains("worship") || combined.contains("church") || combined.contains("hymn") || combined.contains("jesus") || combined.contains("papuri") -> "CHRISTIAN"
            combined.contains("christmas") || combined.contains("pasko") || combined.contains("santa") || combined.contains("xmas") -> "CHRISTMAS"
            combined.contains("pambata") || combined.contains("nursery") || combined.contains("rhyme") || combined.contains("kids") || combined.contains("disney") -> "CHILDREN"
            combined.contains("rock") || combined.contains("band") -> "ROCK"
            combined.contains("country") -> "COUNTRY"
            combined.contains("disco") || combined.contains("dance") -> "DISCO"
            combined.contains("sound effect") || combined.contains("fanfare") || combined.contains("jingle") -> "SOUND_EFFECTS"
            else -> "OPM"
        }
    }
